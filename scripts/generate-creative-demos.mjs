// Writes the flagship creative demonstrations from the real engine.
//
//   npm run demo:creative
//
// Vite is already a dependency of the test suite; it is used here only to load the TypeScript domain
// module. Nothing is fetched, no font or photograph is downloaded, and the output is deterministic.

import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createServer } from 'vite';

const root = process.cwd();
const server = await createServer({
  configFile: false,
  root,
  appType: 'custom',
  logLevel: 'error',
  server: { middlewareMode: true },
  resolve: { alias: { '@': path.join(root, 'src') } },
});

try {
  const { generateCreativeDemoDocuments } = await server.ssrLoadModule('/src/lib/domain/creative-demos.ts');
  const documents = generateCreativeDemoDocuments();
  const directory = path.join(root, 'docs', 'creative-demos');
  await mkdir(directory, { recursive: true });

  for (const document of documents) {
    await writeFile(path.join(directory, `${document.slug}.md`), document.markdown, 'utf8');
    const json = {
      format: 'dof-creative-demo/1',
      synthetic: true,
      slug: document.slug,
      brief: document.brief,
      direction: document.direction,
    };
    await writeFile(path.join(directory, `${document.slug}.json`), `${JSON.stringify(json, null, 2)}\n`, 'utf8');
    console.log(`wrote docs/creative-demos/${document.slug}.md and .json`);
  }
  console.log(`\n${documents.length} demonstrations generated by the deterministic engine.`);
} finally {
  await server.close();
}
